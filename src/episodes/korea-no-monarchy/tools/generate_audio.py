"""Create the episode voice and timeline from measured audio, not assumed timing."""
import asyncio, hashlib, json, math, subprocess
from pathlib import Path
import edge_tts

ROOT=Path(__file__).resolve().parents[4]
EP=ROOT/'src/episodes/korea-no-monarchy'
PUBLIC=ROOT/'public/episodes/korea-no-monarchy/audio/narration'
PROBE=ROOT/'node_modules/@remotion/compositor-linux-x64-gnu/ffprobe'
VOICE='ko-KR-HyunsuMultilingualNeural'
RATE='+10%'
PITCH='-4Hz'
FPS=30

async def main():
 rows=json.loads((EP/'data/script.json').read_text())
 PUBLIC.mkdir(parents=True,exist_ok=True)
 meta=EP/'data/voice-metadata';meta.mkdir(exist_ok=True)
 sem=asyncio.Semaphore(3)
 async def one(b):
  name=b['scriptId'].lower();audio=PUBLIC/f'{name}.mp3'
  signature=hashlib.sha256((b['ko']+VOICE+RATE+PITCH).encode()).hexdigest()
  key=meta/f'{name}.sha256'
  async with sem:
   if not(audio.exists() and key.exists() and key.read_text()==signature):
    for attempt in range(3):
     try:
      await edge_tts.Communicate(b['ko'],VOICE,rate=RATE,pitch=PITCH,boundary='SentenceBoundary').save(str(audio),str(meta/f'{name}.jsonl'))
      key.write_text(signature);break
     except Exception:
      if attempt==2:raise
      await asyncio.sleep(2*(attempt+1))
   print('voice ready:',b['scriptId'],flush=True)
 await asyncio.gather(*(one(b) for b in rows))
 timeline=[];captions=[];cursor=0
 for b in rows:
  path=PUBLIC/f"{b['scriptId'].lower()}.mp3"
  duration=float(subprocess.check_output([str(PROBE),'-v','error','-show_entries','format=duration','-of','default=nw=1:nk=1',str(path)],text=True))
  frames=math.ceil(duration*FPS)
  gap=8 if b['id']!='K36' else 28
  timeline.append({**b,'startFrame':cursor,'voiceFrames':frames,'durationInFrames':frames+gap,'durationSec':duration,'file':f"episodes/korea-no-monarchy/audio/narration/{path.name}",'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
  for line in (meta/f"{b['scriptId'].lower()}.jsonl").read_text().splitlines():
   c=json.loads(line)
   if c.get('type')=='SentenceBoundary':
    offset=c['offset']/10000;length=c['duration']/10000
    captions.append({'text':c['text'],'startMs':cursor/FPS*1000+offset,'endMs':cursor/FPS*1000+offset+length,'scriptId':b['scriptId'],'timing':'SentenceBoundary'})
  cursor+=frames+gap
 result={'fps':FPS,'durationInFrames':cursor,'durationSec':cursor/FPS,'voice':VOICE,'rate':RATE,'pitch':PITCH,'beats':timeline,'captions':captions}
 (EP/'data/timing.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
 (EP/'duration.ts').write_text(f'// Measured voice durations, generated by tools/generate_audio.py.\nexport const EPISODE_FRAMES = {cursor};\n')
 print(json.dumps({'beats':len(rows),'frames':cursor,'seconds':cursor/FPS,'captions':len(captions)},ensure_ascii=False),flush=True)

if __name__=='__main__':asyncio.run(main())
